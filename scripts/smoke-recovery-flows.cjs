// Mutates only the dedicated disposable browser-check installation.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const crypto = require('node:crypto')
function totp(secret) {
  let bits = ''
  for (const c of secret) bits += 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567'.indexOf(c).toString(2).padStart(5, '0')
  const key = Buffer.from(bits.match(/.{8}/g).map(x => parseInt(x, 2)))
  const step = Buffer.alloc(8); step.writeBigUInt64BE(BigInt(Math.floor(Date.now() / 30000)))
  const digest = crypto.createHmac('sha1', key).update(step).digest(); const offset = digest[19] & 15
  return String((digest.readUInt32BE(offset) & 0x7fffffff) % 1000000).padStart(6, '0')
}
async function main() {
  const base = process.env.SMOKE_BASE_URL
  assert(base?.endsWith(':8091'), 'Fixture creation is restricted to the disposable UI check port')
  const browser = await chromium.launch({ args: ['--no-sandbox'] })
  try {
    const context = await browser.newContext()
    const page = await context.newPage()
    const errors = []; page.on('pageerror', e => errors.push(e.message))
    await page.goto(base + '/login')
    await page.getByPlaceholder('you@company.com or your username').fill(process.env.SMOKE_USERNAME)
    await page.locator('input[type=password]').fill(process.env.SMOKE_PASSWORD)
    await Promise.all([page.waitForURL('**/dashboard'), page.getByRole('button', { name: 'Sign in', exact: true }).click()])
    const token = await page.evaluate(() => localStorage.getItem('access_token'))
    const headers = { Authorization: `Bearer ${token}` }
    const api = async (method, path, data) => {
      const response = await context.request[method](base + '/api/v1' + path, { headers, data })
      assert(response.ok(), `${method} ${path}: ${response.status()}`)
      return response.status() === 204 ? null : response.json()
    }
    const calendar = await api('get', '/settings/calendar')
    const date = offset => { const d = new Date(calendar.today + 'T12:00:00Z'); d.setUTCDate(d.getUTCDate() + offset); return d.toISOString().slice(0, 10) }
    const type = await api('post', '/record-types', { name: 'Browser recovery ' + Date.now(), fields: [{ name: 'Renewal date', field_type: 'date' }, { name: 'Private text', field_type: 'secret' }] })
    await api('put', `/record-types/${type.id}`, { reminder_field_id: type.fields[0].id })
    const soon = await api('post', `/records/by-type/${type.id}`, { name: 'Browser due fixture', values: [{ field_id: type.fields[0].id, value: date(2) }, { field_id: type.fields[1].id, value: 'DISPOSABLE_PRIVATE_FIXTURE' }] })
    await api('post', `/records/by-type/${type.id}`, { name: 'Browser future fixture', values: [{ field_id: type.fields[0].id, value: date(90) }] })
    await page.goto(`${base}/records/${type.slug}`)
    await page.getByRole('button', { name: soon.name, exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Browser future fixture', exact: true }).count(), 0)
    await page.getByRole('button', { name: 'All records', exact: true }).click()
    await page.getByRole('button', { name: 'Browser future fixture', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Save as my starting view', exact: true }).click()
    await page.reload()
    await page.getByRole('button', { name: 'Browser future fixture', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Reset starting view', exact: true }).click()
    await page.getByRole('button', { name: 'Browser future fixture', exact: true }).waitFor({ state: 'hidden' })
    await page.goto(`${base}/records/${type.slug}/${soon.id}`)
    await page.getByRole('button', { name: /Protected.*Reveal/ }).click()
    await page.getByLabel('Reveal current password').fill(process.env.SMOKE_PASSWORD)
    await page.getByRole('button', { name: 'Reveal for 30 seconds', exact: true }).click()
    await page.getByText('DISPOSABLE_PRIVATE_FIXTURE', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Hide value', exact: true }).click()
    assert.equal(await page.getByText('DISPOSABLE_PRIVATE_FIXTURE', { exact: true }).count(), 0)
    await api('delete', `/records/${soon.id}`)
    await page.goto(base + '/trash')
    const row = page.getByRole('row').filter({ hasText: soon.name })
    await row.getByRole('button', { name: 'Restore', exact: true }).click()
    await row.waitFor({ state: 'hidden' })
    assert.equal((await api('get', `/records/${soon.id}`)).id, soon.id)
    await page.goto(base + '/settings/security')
    await page.getByLabel('MFA current password').fill(process.env.SMOKE_PASSWORD)
    await page.getByRole('button', { name: 'Set up authenticator', exact: true }).click()
    const section = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Authenticator security', exact: true }) })
    await section.locator('code').waitFor()
    const secret = await section.locator('code').innerText()
    await page.getByLabel('MFA verification code').fill(totp(secret))
    await page.getByRole('button', { name: 'Verify and enable', exact: true }).click()
    await section.locator('pre').waitFor()
    const recovery = (await section.locator('pre').innerText()).split('\n')
    assert.equal(recovery.length, 8)
    await page.getByRole('button', { name: 'I saved my recovery codes', exact: true }).click()
    await page.getByLabel('MFA current password').fill(process.env.SMOKE_PASSWORD)
    await page.getByLabel('MFA verification code').fill('invalid-code')
    await page.getByRole('button', { name: 'Disable authenticator', exact: true }).click()
    await section.getByRole('alert').waitFor()
    assert(page.url().endsWith('/settings/security'), 'Invalid step-up must not sign the user out')
    await page.getByLabel('MFA verification code').fill(recovery[0])
    await page.getByRole('button', { name: 'Disable authenticator', exact: true }).click()
    await page.getByRole('button', { name: 'Set up authenticator', exact: true }).waitFor()
    assert.deepEqual(errors, [])
    console.log('SMOKE_OK: saved starting view, expiry default, protected reveal/hide, Trash restore, MFA enrollment, invalid step-up and recovery')
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exit(1) })
